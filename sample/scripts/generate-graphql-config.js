#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const localPropertiesPath = path.join(rootDir, 'android', 'local.properties');
const outputPath = path.join(rootDir, 'src', 'config', 'graphql.generated.ts');

function parseKeyValueFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }

  return fs
    .readFileSync(filePath, 'utf8')
    .split(/\r?\n/)
    .reduce((values, line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) {
        return values;
      }

      const separatorIndex = trimmed.indexOf('=');
      if (separatorIndex === -1) {
        return values;
      }

      const key = trimmed.slice(0, separatorIndex).trim();
      const value = trimmed.slice(separatorIndex + 1).trim();
      values[key] = value.replace(/^['"]|['"]$/g, '');
      return values;
    }, {});
}

const dotEnv = parseKeyValueFile(envPath);
const localProperties = parseKeyValueFile(localPropertiesPath);

const graphqlServerUrl =
  process.env.GRAPHQL_SERVER_URL ||
  dotEnv.GRAPHQL_SERVER_URL ||
  localProperties.GraphQLServerUrl;

const graphqlAuthKey =
  process.env.CLOUD_DEVELOPER_KEY ||
  dotEnv.CLOUD_DEVELOPER_KEY ||
  localProperties.GraphQLAuthKey;

const missingKeys = [];
if (!graphqlServerUrl) {
  missingKeys.push('GRAPHQL_SERVER_URL or android/local.properties GraphQLServerUrl');
}
if (!graphqlAuthKey) {
  missingKeys.push('CLOUD_DEVELOPER_KEY or android/local.properties GraphQLAuthKey');
}

if (missingKeys.length > 0) {
  console.error(`Missing GraphQL config: ${missingKeys.join(', ')}.`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(outputPath), {recursive: true});
fs.writeFileSync(
  outputPath,
  [
    '// Generated by scripts/generate-graphql-config.js. Do not commit local values.',
    'export const graphqlConfig = {',
    `  serverUrl: ${JSON.stringify(graphqlServerUrl)},`,
    `  authKey: ${JSON.stringify(graphqlAuthKey)},`,
    '} as const;',
    '',
  ].join('\n'),
);

console.log('Generated src/config/graphql.generated.ts');
